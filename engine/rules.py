def broker_for_month(month: int) -> dict:
    if month not in range(1, 13):
        raise ValueError(f"месяц вне диапазона: {month}")
    for broker in BROKERS.values():
        if month in broker["months"]:
            return broker
    raise RuntimeError("брокер не найден")
